"""Build the files needed to load the P6R (UMR + UR12e) into the ENG-654 web simulators.

    python sim/build_sim_assets.py          (run from the repository root)

Writes
    sim/meshes/*.stl              binary STL visuals (UR10e/12e links + UMR base box)
    sim/umr_ur12e_sim.urdf        umr_urdf/umr_ur12e.urdf + <visual> meshes + colours

Why STL and not the original .dae files?
    The UR .dae meshes declare <up_axis>Z_UP</up_axis>. The course simulators load
    Collada with three.js' ColladaLoader, which then rotates the mesh by -90 deg about X
    to make it "Y-up". The links would appear rotated. Converting to STL keeps the
    geometry in the frame ROS uses (checked against the UR collision STLs).

The simulators also draw only <mesh> geometry (the <box> of the UMR is ignored), so the
base is exported as an STL box too. Joints are copied unchanged, so the kinematics
(and therefore every result from p6r/kinematics.py) is identical.
"""
from pathlib import Path
import copy
import xml.etree.ElementTree as ET

import numpy as np
import trimesh

ROOT = Path(__file__).resolve().parents[1]
DAE_DIR = ROOT / 'ur12e' / 'meshes' / 'ur10e' / 'visual'
OUT_MESH = ROOT / 'sim' / 'meshes'
SRC_URDF = ROOT / 'umr_urdf' / 'umr_ur12e.urdf'
OUT_URDF = ROOT / 'sim' / 'umr_ur12e_sim.urdf'

# link -> (mesh stem, visual origin xyz, rpy, material); origins copied from ur12e/ur12e.urdf
UR_VISUALS = {
    'base_link_inertia': ('base',     (0, 0, 0),              (0, 0, np.pi),              'ur_dark'),
    'shoulder_link':     ('shoulder', (0, 0, 0),              (0, 0, np.pi),              'ur_grey'),
    'upper_arm_link':    ('upperarm', (0, 0, 0.1762),         (np.pi / 2, 0, -np.pi / 2), 'ur_grey'),
    'forearm_link':      ('forearm',  (0, 0, 0.0393),         (np.pi / 2, 0, -np.pi / 2), 'ur_grey'),
    'wrist_1_link':      ('wrist1',   (0, 0, -0.135),         (np.pi / 2, 0, 0),          'ur_blue'),
    'wrist_2_link':      ('wrist2',   (0, 0, -0.12),          (0, 0, 0),                  'ur_blue'),
    'wrist_3_link':      ('wrist3',   (0, -0.0005, -0.1168),  (np.pi / 2, 0, 0),          'ur_dark'),
}
MATERIALS = {'umr_body': '0.20 0.22 0.25 1', 'ur_grey': '0.78 0.80 0.82 1',
             'ur_blue': '0.36 0.60 0.80 1', 'ur_dark': '0.25 0.27 0.30 1'}
UMR_SIZE, H_MOUNT = (0.83, 0.54, 0.41), 0.41


def convert_meshes():
    OUT_MESH.mkdir(parents=True, exist_ok=True)
    for stem, *_ in UR_VISUALS.values():
        scene = trimesh.load(DAE_DIR / f'{stem}.dae', force='scene')
        mesh = scene.to_geometry() if hasattr(scene, 'to_geometry') else scene.dump(concatenate=True)
        mesh.export(OUT_MESH / f'ur12e_{stem}.stl')          # binary STL, metres
        print(f'  ur12e_{stem}.stl  {len(mesh.faces):6d} faces')
    box = trimesh.creation.box(extents=UMR_SIZE)
    box.export(OUT_MESH / 'umr_base.stl')
    print('  umr_base.stl')


def _f(v):
    return ' '.join(f'{float(x):.10g}' for x in v)


def _visual(link, filename, xyz, rpy, material):
    vis = ET.SubElement(link, 'visual')
    ET.SubElement(vis, 'origin', xyz=_f(xyz), rpy=_f(rpy))
    geo = ET.SubElement(vis, 'geometry')
    ET.SubElement(geo, 'mesh', filename=f'meshes/{filename}')
    ET.SubElement(vis, 'material', name=material)


def build_urdf():
    tree = ET.parse(SRC_URDF)
    robot = tree.getroot()
    robot.set('name', 'umr_ur12e_sim')
    for name, rgba in MATERIALS.items():                     # global material table
        m = ET.Element('material', name=name)
        ET.SubElement(m, 'color', rgba=rgba)
        robot.insert(0, m)
    links = {l.get('name'): l for l in robot.findall('link')}
    # UMR base: replace the <box> visual (ignored by the simulators) with the STL box
    umr = links['umr_base_link']
    for v in umr.findall('visual'):
        umr.remove(v)
    _visual(umr, 'umr_base.stl', (0, 0, H_MOUNT / 2), (0, 0, 0), 'umr_body')
    for link, (stem, xyz, rpy, mat) in UR_VISUALS.items():
        _visual(links[link], f'ur12e_{stem}.stl', xyz, rpy, mat)
    ET.indent(tree, space='  ')
    header = ('<?xml version="1.0"?>\n<!-- Generated by sim/build_sim_assets.py from '
              'umr_urdf/umr_ur12e.urdf. Same joints; adds STL visuals for the ENG-654 web '
              'simulators. Movable-joint order: base_x_joint, shoulder_pan, shoulder_lift, '
              'elbow, wrist_1, wrist_2, wrist_3  ==  Q = [x, q1..q6]. -->\n')
    OUT_URDF.write_text(header + ET.tostring(robot, encoding='unicode') + '\n', encoding='utf-8')
    print('wrote', OUT_URDF.relative_to(ROOT))


if __name__ == '__main__':
    convert_meshes()
    build_urdf()
